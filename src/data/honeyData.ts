function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

export function generateUniqueDiscoveryProfile(
  filter: DeckFilter,
  selectedCountry: string,
  usedKeys: Set<string>
): Profile {
  const matchingCountries =
    selectedCountry === 'All Countries'
      ? COUNTRY_CATALOG
      : COUNTRY_CATALOG.filter((c) => c.country === selectedCountry);
  const countryPool = matchingCountries.length > 0 ? matchingCountries : COUNTRY_CATALOG;

  for (let attempt = 0; attempt < 40; attempt += 1) {
    const entry = pick(countryPool);
    const gender: 'woman' | 'man' =
      filter === 'woman'
        ? 'woman'
        : filter === 'man'
          ? 'man'
          : Math.random() < 0.54
            ? 'woman'
            : 'man';

    const first =
      gender === 'woman' ? pick(entry.femaleFirst) : pick(entry.maleFirst);
    const last = pick(entry.lastNames);
    const fullName = `${first} ${last}`;
    const city = pick(entry.cities);
    const key = `${fullName}|${city}|${entry.country}`;

    if (usedKeys.has(key) && attempt < 35) {
      continue;
    }

    usedKeys.add(key);

    const portraitPool =
      gender === 'woman' ? entry.femalePortraits : entry.malePortraits;
    const portraitUrl = pick(portraitPool);

    // ~76% realistic photo, ~12% no profile photo, ~12% login-style initials avatar
    const roll = Math.random();
    const avatarMode: ProfileAvatarMode =
      roll < 0.76 ? 'photo' : roll < 0.88 ? 'none' : 'login-avatar';

    const uniqueSuffix = Math.floor(100 + Math.random() * 899);
    const username = `${first.toLowerCase().replace(/[^a-z]/g, '')}.${city
      .toLowerCase()
      .replace(/[^a-z]/g, '')
      .slice(0, 5)}${uniqueSuffix}`;

    return {
      id: `prof-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
      memberId: `HC-${1000 + Math.floor(Math.random() * 8999)}`,
      name: fullName,
      username,
      age: 22 + Math.floor(Math.random() * 12),
      gender,
      city,
      country: entry.country,
      nativeLanguage: entry.language,
      portraitUrl,
      avatarMode,
      bio: pick(BIOS),
      flirtyPromptLine: pick(FLIRTY_LINES),
      interests: pick(INTEREST_POOLS),
      isOnline: Math.random() < 0.82,
      // Verified badge appears on ~42% of profiles, NOT on everyone
      verified: Math.random() < 0.42,
    };
  }

  // Fallback guaranteed unique entry
  const fallback = pick(countryPool);
  const g: 'woman' | 'man' = filter === 'man' ? 'man' : 'woman';
  const f = g === 'woman' ? pick(fallback.femaleFirst) : pick(fallback.maleFirst);
  const l = pick(fallback.lastNames);
  return {
    id: `prof-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
    memberId: `HC-${1000 + Math.floor(Math.random() * 8999)}`,
    name: `${f} ${l}`,
    username: `${f.toLowerCase()}.${Date.now().toString().slice(-4)}`,
    age: 24 + Math.floor(Math.random() * 8),
    gender: g,
    city: pick(fallback.cities),
    country: fallback.country,
    nativeLanguage: fallback.language,
    portraitUrl: pick(g === 'woman' ? fallback.femalePortraits : fallback.malePortraits),
    avatarMode: 'photo',
    bio: pick(BIOS),
    flirtyPromptLine: pick(FLIRTY_LINES),
    interests: pick(INTEREST_POOLS),
    isOnline: true,
    verified: Math.random() < 0.42,
  };
}

